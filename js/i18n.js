const I18N = {
  lang: "en",
  changeListeners: [],

  t(key, vars) {
    const dict = I18N_DICT[this.lang] || I18N_DICT.en;
    let str = dict[key] !== undefined ? dict[key] : (I18N_DICT.en[key] !== undefined ? I18N_DICT.en[key] : key);
    if (vars) {
      Object.keys(vars).forEach((k) => {
        str = str.replace(new RegExp("\\{\\{" + k + "\\}\\}", "g"), vars[k]);
      });
    }
    return str;
  },

  // Picks singular/plural English or invariant Arabic phrasing for counts.
  plural(n, singularKey, pluralKey, vars) {
    const key = n === 1 ? singularKey : pluralKey;
    return this.t(key, Object.assign({ n }, vars || {}));
  },

  // Locale tag for Intl date/time formatting. Arabic uses Latin digits
  // (via the -u-nu-latn extension) so numbers stay unambiguous in a
  // business context, while month/weekday names render in Arabic.
  localeTag() {
    return this.lang === "ar" ? "ar-SY-u-nu-latn" : "en-US";
  },

  onChange(fn) {
    this.changeListeners.push(fn);
  },

  applyDom(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.setAttribute("placeholder", this.t(el.getAttribute("data-i18n-ph")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", this.t(el.getAttribute("data-i18n-title")));
    });
  },

  applyDirection() {
    document.documentElement.lang = this.lang;
    document.documentElement.dir = this.lang === "ar" ? "rtl" : "ltr";
    // Mirrors the head's paint-time script (see index.html) so the next
    // load starts in the right direction before IndexedDB has opened.
    try { localStorage.setItem("crm-lang", this.lang); } catch (e) { /* ignore */ }
  },

  async setLang(lang, opts) {
    opts = opts || {};
    this.lang = lang === "ar" ? "ar" : "en";
    this.applyDirection();
    this.applyDom();
    if (!opts.skipPersist) {
      await Settings.update({ language: this.lang });
    }
    for (const fn of this.changeListeners) {
      try { await fn(this.lang); } catch (e) { /* keep other listeners running */ }
    }
  },

  async init() {
    const settings = await Settings.get();
    this.lang = settings.language === "ar" ? "ar" : "en";
    this.applyDirection();
    this.applyDom();
  },
};

